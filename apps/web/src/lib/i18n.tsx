export type Lang = 'pt-BR' | 'en';
const DICTS: Record<Lang, Record<MessageKey, string>> = { 'pt-BR': ptBR, en };

function readLang(): Lang {
  try {
    const stored = localStorage.getItem('ca-lang');
    if (stored === 'en' || stored === 'pt-BR') return stored;
  } catch {
    /* sem armazenamento */
  }
  return 'pt-BR';
}

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: MessageKey) => string;
}

const I18nCtx = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    document.documentElement.lang = l;
    try {
      localStorage.setItem('ca-lang', l);
    } catch {
      /* sem armazenamento */
    }
  }, []);
  const value = useMemo<I18nValue>(() => ({ lang, setLang, t: (key) => DICTS[lang][key] }), [lang, setLang]);
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n(): I18nValue {
  const v = useContext(I18nCtx);
  if (!v) throw new Error('I18nProvider ausente');
  return v;
}
